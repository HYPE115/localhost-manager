import os
import threading
import subprocess
import json
from flask import Flask, render_template, jsonify, request
from flask_socketio import SocketIO, emit
from pyngrok import ngrok
from dotenv import load_dotenv

# Charger les variables d'environnement
load_dotenv()

app = Flask(__name__)
app.config['SECRET_KEY'] = 'dev'
socketio = SocketIO(app)

# Dictionnaire pour stocker les tunnels actifs
active_tunnels = {}

# Configuration Ngrok
NGROK_AUTH_TOKEN = os.getenv('NGROK_AUTH_TOKEN')
if NGROK_AUTH_TOKEN:
    ngrok.set_auth_token(NGROK_AUTH_TOKEN)

@app.route('/')
def index():
    return render_template('index.html', tunnels=active_tunnels)

@app.route('/api/tunnels', methods=['GET'])
def get_tunnels():
    return jsonify(active_tunnels)

@app.route('/api/tunnels', methods=['POST'])
def create_tunnel():
    data = request.json
    local_port = data.get('port')
    protocol = data.get('protocol', 'http')
    
    if not local_port:
        return jsonify({'error': 'Port is required'}), 400
    
    try:
        # Créer un nouveau tunnel
        public_url = ngrok.connect(addr=local_port, proto=protocol).public_url
        tunnel_info = {
            'local_port': local_port,
            'public_url': public_url,
            'protocol': protocol
        }
        active_tunnels[public_url] = tunnel_info
        
        # Envoyer la mise à jour à tous les clients
        socketio.emit('tunnel_update', {'action': 'created', 'tunnel': tunnel_info})
        
        return jsonify(tunnel_info)
    except Exception as e:
        return jsonify({'error': str(e)}), 500

@app.route('/api/tunnels/<path:public_url>', methods=['DELETE'])
def close_tunnel(public_url):
    if public_url not in active_tunnels:
        return jsonify({'error': 'Tunnel not found'}), 404
    
    try:
        # Fermer le tunnel
        ngrok.disconnect(public_url)
        tunnel_info = active_tunnels.pop(public_url)
        
        # Envoyer la mise à jour à tous les clients
        socketio.emit('tunnel_update', {'action': 'deleted', 'tunnel': tunnel_info})
        
        return jsonify({'status': 'success'})
    except Exception as e:
        return jsonify({'error': str(e)}), 500

if __name__ == '__main__':
    # Créer le dossier templates s'il n'existe pas
    os.makedirs('templates', exist_ok=True)
    
    # Lancer l'application
    socketio.run(app, debug=True, port=5000)





























































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































